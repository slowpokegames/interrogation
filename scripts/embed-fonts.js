// Builds assets/css/fonts.css with the fonts inlined as data URIs, so pages
// opened straight from disk (file://) get the real fonts. Run: node scripts/embed-fonts.js
"use strict";
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "..", "assets", "fonts");
const faces = [
  ["Monoton", 400, "monoton.woff2"],
  ["Special Elite", 400, "special-elite.woff2"],
  ["Barlow Condensed", 500, "barlow-condensed-500.woff2"],
  ["Barlow Condensed", 600, "barlow-condensed-600.woff2"],
  ["Barlow Condensed", 700, "barlow-condensed-700.woff2"],
  ["Barlow", 400, "barlow-400.woff2"],
  ["Barlow", 600, "barlow-600.woff2"]
];

let css = "/* Generated by scripts/embed-fonts.js — do not edit. Fonts: SIL Open Font License (see assets/fonts/OFL.txt). */\n";
for (const [family, weight, file] of faces) {
  const data = fs.readFileSync(path.join(dir, file)).toString("base64");
  css += `@font-face { font-family: "${family}"; font-weight: ${weight}; font-display: swap; src: url(data:font/woff2;base64,${data}) format("woff2"); }\n`;
}
fs.writeFileSync(path.join(__dirname, "..", "assets", "css", "fonts.css"), css);
console.log("wrote assets/css/fonts.css (" + Math.round(css.length / 1024) + " KB)");
